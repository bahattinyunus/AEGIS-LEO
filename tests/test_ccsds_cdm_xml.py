def test_miss_distance_verification():
    cdm = parse_cdm_xml(SAMPLE_XML_CDM)
    is_ok, calc_m, rec_m = cdm.verify_miss_distance(tolerance_m=1.0)
    # sqrt(24.5^2 + 182.1^2 + (-15.3)^2) = sqrt(600.25 + 33160.41 + 234.09) = sqrt(33994.75) = 184.376 m
    # Recorded is 184.25 m -> difference ~0.126 m <= 1.0 m
    assert is_ok
    assert abs(calc_m - rec_m) < 0.2


def test_relative_speed_verification():
    cdm = parse_cdm_xml(SAMPLE_XML_CDM)
    is_ok, calc_v, rec_v = cdm.verify_relative_speed(tolerance_m_s=10.0)
