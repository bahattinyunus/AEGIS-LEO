def test_covariance_3x3_reconstruction():
    cov = CDMCovariance(
        ref_frame="RTN",
        cr_r=50.0,
        ct_r=10.0,
        ct_t=200.0,
        cn_r=2.0,
        cn_t=5.0,
        cn_n=80.0,
    )
    mat = cov.to_pos_covariance_matrix()
    assert mat.shape == (3, 3)
    # Check symmetry
    assert np.allclose(mat, mat.T)
    # Check values
    assert mat[0, 0] == 50.0
    assert mat[1, 1] == 200.0
    assert mat[2, 2] == 80.0
    assert mat[0, 1] == 10.0
    assert mat[0, 2] == 2.0
    assert mat[1, 2] == 5.0

    # 1-sigma extraction
    sig_r, sig_t, sig_n = cov.one_sigma_position_errors()
    assert np.isclose(sig_r, np.sqrt(50.0))
    assert np.isclose(sig_t, np.sqrt(200.0))
    assert np.isclose(sig_n, np.sqrt(80.0))

    # PSD check
    is_psd, min_eig = cov.is_positive_semidefinite()
    assert is_psd
    assert min_eig > 0.0


def test_covariance_6x6_full_ingestion():
    # Build a known 6x6 positive definite matrix
    a = np.random.RandomState(42).randn(6, 6)
    expected_cov6 = np.dot(a, a.T) + np.eye(6) * 10.0

    cov = CDMCovariance.from_matrix(expected_cov6, ref_frame="RTN")
    reconstructed = cov.to_full_covariance_matrix()

    assert reconstructed.shape == (6, 6)
    assert np.allclose(reconstructed, reconstructed.T)
    assert np.allclose(reconstructed, expected_cov6)


def test_covariance_non_psd_detection():
    # Negative variance on diagonal
    bad_cov = CDMCovariance(
        ref_frame="RTN",
        cr_r=-10.0,
        ct_t=100.0,
        cn_n=50.0,
    )
    is_psd, min_eig = bad_cov.is_positive_semidefinite()
    assert not is_psd
    assert min_eig < 0.0


