def test_create_cdm_message_and_to_dict():
    r1 = np.array([6878.137, 0.0, 0.0])
    v1 = np.array([0.0, 7.612, 0.0])
    r2 = np.array([6878.237, 0.1, 0.0])
    v2 = np.array([0.0, -7.612, 0.0])

    cov1 = np.diag([100.0, 400.0, 100.0])
    cov2 = np.diag([500.0, 2000.0, 500.0])

    tca = datetime(2026, 11, 20, 12, 0, 0, tzinfo=timezone.utc)

    cdm = create_cdm_message(
        primary_sat_id="44713",
        primary_sat_name="STARLINK-1007",
        secondary_obj_id="99999",
        secondary_obj_name="DEBRIS-TEST",
        miss_distance_m=141.42,
        relative_speed_m_s=15224.0,
        collision_prob=2.5e-4,
        tca=tca,
        primary_state=(r1, v1),
        secondary_state=(r2, v2),
        primary_cov_rtn_m2=cov1,
        secondary_cov_rtn_m2=cov2,
    )

    assert cdm.header.originator == "AEGIS-LEO SSA SHIELD"
    assert cdm.relative_metadata.miss_distance == 141.42
    assert cdm.object1.metadata.object_name == "STARLINK-1007"

    # Export to dict
    d = cdm.to_dict()
    assert d["ccsds_cdm_vers"] == "1.0"
    assert d["miss_distance_m"] == 141.42
    assert d["alert_status"] == "CRITICAL"  # Pc > 1e-4
    assert d["covariance_matrix_rtn_m2"]["c_rr"] == 100.0
    assert d["covariance_matrix_rtn_m2"]["c_tt"] == 400.0

    # Export to XML and KVN
    xml_out = cdm.to_xml()
    assert "<cdm" in xml_out
    assert "STARLINK-1007" in xml_out

    kvn_out = cdm.to_kvn()
    assert "CCSDS_CDM_VERS" in kvn_out
    assert "STARLINK-1007" in kvn_out


def test_validation_failure_modes():
    # Test missing TCA or negative miss distance
    bad_rel = CDMRelativeMetadata(
        tca=datetime.now(timezone.utc),
        miss_distance=-50.0,  # Negative miss distance
        collision_probability=1.5,  # Probability > 1.0
    )
    bad_obj1 = CDMObject(metadata=CDMObjectMetadata(object="OBJECT1", object_designator=""))
    bad_obj2 = CDMObject(metadata=CDMObjectMetadata(object="OBJECT2", object_designator=""))

    bad_cdm = CDMMessage(
        header=CDMHeader(ccsds_cdm_vers="1.0", originator="", message_id=""),
        relative_metadata=bad_rel,
        object1=bad_obj1,
        object2=bad_obj2,
    )

    res = bad_cdm.validate()
    assert not res.is_valid
    assert any("MISS_DISTANCE" in e for e in res.errors)
    assert any("COLLISION_PROBABILITY" in e for e in res.errors)
    assert any("ORIGINATOR" in e for e in res.errors)
    assert any("Object 1" in e for e in res.errors)
