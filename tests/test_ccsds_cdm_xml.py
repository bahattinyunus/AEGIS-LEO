def test_screening_volume_sphere():
    meta = CDMRelativeMetadata(
        tca=datetime.now(timezone.utc),
        miss_distance=150.0,
        screen_volume_shape="SPHERE",
        screen_volume_radius=500.0,
    )
    # Inside sphere (r = 300 m)
    assert meta.is_position_in_screening_volume([200.0, 200.0, 100.0])
    # Outside sphere (r = 600 m)
    assert not meta.is_position_in_screening_volume([500.0, 300.0, 200.0])


def test_screening_volume_box():
    meta = CDMRelativeMetadata(
        tca=datetime.now(timezone.utc),
        miss_distance=150.0,
        screen_volume_shape="BOX",
        screen_volume_x=2000.0,  # [-1000, 1000]
        screen_volume_y=10000.0, # [-5000, 5000]
        screen_volume_z=2000.0,  # [-1000, 1000]
    )
    assert meta.is_position_in_screening_volume([500.0, 3000.0, -800.0])
    assert not meta.is_position_in_screening_volume([1200.0, 3000.0, 100.0])


def test_screening_volume_ellipsoid():
    meta = CDMRelativeMetadata(
        tca=datetime.now(timezone.utc),
        miss_distance=150.0,
        screen_volume_shape="ELLIPSOID",
        screen_volume_x=1000.0,
        screen_volume_y=5000.0,
        screen_volume_z=1000.0,
    )
    # (500/1000)^2 + (2000/5000)^2 + (500/1000)^2 = 0.25 + 0.16 + 0.25 = 0.66 <= 1.0 -> True
    assert meta.is_position_in_screening_volume([500.0, 2000.0, 500.0])
    # Outside: x = 1200 m > a
    assert not meta.is_position_in_screening_volume([1200.0, 0.0, 0.0])


