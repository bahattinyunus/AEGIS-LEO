def test_parse_ccsds_timestamp_iso():
    ts = "2026-11-15T04:12:30.500Z"
    dt = parse_ccsds_timestamp(ts)
    assert dt.year == 2026
    assert dt.month == 11
    assert dt.day == 15
    assert dt.hour == 4
    assert dt.minute == 12
    assert dt.second == 30
    assert dt.microsecond == 500000
    assert dt.tzinfo == timezone.utc


def test_parse_ccsds_timestamp_day_of_year():
    # Day 319 of 2026 is November 15
    ts = "2026-319T04:12:30.250"
    dt = parse_ccsds_timestamp(ts)
    assert dt.year == 2026
    assert dt.month == 11
    assert dt.day == 15
    assert dt.hour == 4
    assert dt.minute == 12
    assert dt.second == 30
    assert dt.microsecond == 250000


def test_format_ccsds_timestamp_roundtrip():
    dt0 = datetime(2026, 8, 20, 14, 25, 40, 123000, tzinfo=timezone.utc)
    formatted = format_ccsds_timestamp(dt0)
    assert formatted == "2026-08-20T14:25:40.123"
    dt_parsed = parse_ccsds_timestamp(formatted)
    assert dt_parsed == dt0


def test_invalid_timestamp():
    with pytest.raises(ValueError):
        parse_ccsds_timestamp("INVALID-DATE-STRING")


